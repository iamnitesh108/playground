// Records the "Under load" and "In production" lessons of the local-cache module: single-flight, failures, absent keys,
// async caches, recursive loads, throughput under threads, per-entry memory, weight-based eviction, soft values, GC impact,
// statistics, Micronaut @Cacheable, pitfalls and a get/put benchmark — from Caffeine 3.1.8 (Java 17), lru-cache 11 (Node 24)
// and moka 0.12 (Rust), plus Micronaut 4.5 with micronaut-cache-caffeine.
//   node capture-runtime.mjs ../../src/modules/local-cache/data/runtime.ts
// Builds the four apps first (Gradle, npm, cargo) and runs every experiment as its own process.
import { execFileSync } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import { homedir, userInfo } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const [, , outFile] = process.argv
if (!outFile) throw new Error('usage: node capture-runtime.mjs <out.ts>')
const HERE = dirname(fileURLToPath(import.meta.url))
const GRADLE = process.env.GRADLE ?? 'gradle'

// ---------- build ----------
const run = (cmd, args, cwd, env = {}) =>
  execFileSync(cmd, args, { cwd, env: { ...process.env, ...env }, maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'pipe'] }).toString()
for (const app of ['runtime-java', 'runtime-micronaut']) run(GRADLE, ['--console=plain', '-q', 'installDist'], join(HERE, app))
if (!existsSync(join(HERE, 'runtime-ts/node_modules'))) run('npm', ['install', '--silent'], join(HERE, 'runtime-ts'))
run('cargo', ['build', '--release', '--quiet'], join(HERE, 'runtime-rust'))

const JAVA = join(HERE, 'runtime-java/build/install/runtime-java/bin/runtime-java')
const MICRONAUT = join(HERE, 'runtime-micronaut/build/install/runtime-micronaut/bin/runtime-micronaut')
const RUST = join(HERE, 'runtime-rust/target/release/local-cache-runtime')
const TS = join(HERE, 'runtime-ts/main.ts')

/** Runs one experiment and keeps the JSON lines it printed (stderr — logs, warnings — is not recorded). */
function events(cmd, args, env = {}, cwd = HERE) {
  process.stderr.write(`  ${[cmd.split('/').pop(), ...args].join(' ')}\n`)
  return run(cmd, args, cwd, env).split('\n').filter((l) => l.startsWith('{')).map((l) => JSON.parse(l))
}
const java = (args, opts = '') => events(JAVA, args, { JAVA_OPTS: opts })
const node = (args, flags = []) => events('node', [...flags, TS, ...args], {}, join(HERE, 'runtime-ts'))
const rust = (args) => events(RUST, args)

const recording = {
  java: [
    ...java(['singleflight']),
    ...java(['throughput', '1']),
    ...java(['footprint'], '-Xmx3g -Xms3g'),
    ...java(['weight']),
    ...['soft', 'strong', 'weight'].flatMap((m) => java(['soft', m], '-Xmx96m')),
    ...[10_000, 200_000, 600_000].flatMap((n) => java(['gc', String(n), '10'], '-Xmx2g -Xms2g -XX:+UseG1GC')),
    ...java(['stats']),
    ...java(['pitfalls']),
    ...java(['bench']),
  ],
  micronaut: events(MICRONAUT, []),
  ts: [
    ...node(['singleflight']),
    ...node(['footprint'], ['--expose-gc']),
    ...node(['weight']),
    ...node(['stats']),
    ...node(['pitfalls']),
    ...node(['bench']),
  ],
  rust: ['singleflight', 'throughput', 'footprint', 'weight', 'stats', 'pitfalls', 'bench'].flatMap((e) => rust([e])),
}

// one "runtime" line per process is enough
for (const key of ['java', 'ts', 'rust']) {
  const first = recording[key].find((e) => e.exp === 'runtime')
  recording[key] = [first, ...recording[key].filter((e) => e.exp !== 'runtime')]
}

const text = JSON.stringify(recording, null, 1)
for (const secret of [userInfo().username, homedir()]) if (text.includes(secret)) throw new Error(`recording contains "${secret}"`)
writeFileSync(
  outFile,
  `// Generated by tools/local-cache-capture/capture-runtime.mjs — do not edit by hand.\n` +
    `// Recorded ${new Date().toISOString().slice(0, 10)} on one machine; benchmarks are medians of a few runs.\n` +
    `import type { RuntimeRecording } from './runtimeTypes'\n\n` +
    `export const RUNTIME: RuntimeRecording = ${text}\n`,
)
console.log(`wrote ${outFile}`)
